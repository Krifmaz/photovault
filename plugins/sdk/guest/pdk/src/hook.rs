//! Exporting hooks.
//!
//! A hook is a plain function `fn(&HookInput) -> Result<HookOutput, Error>`.
//! [`photovault_plugin!`](crate::photovault_plugin) turns it into the Extism
//! export the host calls: it reads the JSON [`HookInput`], calls the function,
//! and writes the JSON [`HookOutput`] or, on `Err`, sets the Extism error
//! (the error's `{:#}` text, so `context` chains are kept) and returns 1.

use crate::Error;
use crate::abi::{FileId, FileInfo, HookEvent, HookInput, HookOutput, HostError};
use serde::de::DeserializeOwned;
use serde_json::Value;

/// The signature every hook function has.
pub type HookFn = fn(&HookInput) -> Result<HookOutput, Error>;

/// Export hook functions as the plugin's Extism exports.
///
/// Each entry is `export_name: function`, where the export name is one of
/// `on_upload`, `on_schedule` and `on_demand` (matching `[hooks]` in
/// `plugin.toml`) and the function is a [`HookFn`]. Invoke it once, at the top
/// level of the plugin crate.
///
/// ```
/// use photovault_plugin_pdk::prelude::*;
///
/// fn handle_demand(input: &HookInput) -> Result<HookOutput> {
///     Ok(HookOutput::default())
/// }
///
/// photovault_plugin_pdk::photovault_plugin! {
///     on_demand: handle_demand,
/// }
/// ```
///
/// On native targets the macro only type-checks the functions, so unit tests
/// link without a Wasm host.
#[macro_export]
macro_rules! photovault_plugin {
    ($($hook:ident : $handler:path),+ $(,)?) => {
        $( $crate::__photovault_export!($hook, $handler); )+
    };
}

/// Implementation detail of [`photovault_plugin!`](crate::photovault_plugin).
#[doc(hidden)]
#[macro_export]
macro_rules! __photovault_export {
    (@export $name:ident, $handler:path) => {
        const _: $crate::hook::HookFn = $handler;

        /// Extism export generated by `photovault_plugin!`.
        #[cfg(target_arch = "wasm32")]
        #[unsafe(no_mangle)]
        pub extern "C" fn $name() -> i32 {
            $crate::hook::__run_export($handler)
        }
    };
    (on_upload, $handler:path) => {
        $crate::__photovault_export!(@export on_upload, $handler);
    };
    (on_schedule, $handler:path) => {
        $crate::__photovault_export!(@export on_schedule, $handler);
    };
    (on_demand, $handler:path) => {
        $crate::__photovault_export!(@export on_demand, $handler);
    };
    ($other:ident, $handler:path) => {
        ::core::compile_error!(::core::concat!(
            "unknown hook `",
            ::core::stringify!($other),
            "`: expected on_upload, on_schedule or on_demand"
        ));
    };
}

/// Decode `input`, run `f`, encode the output. Shared by the Wasm export and
/// [`crate::testing::run_hook`] so both use the same wire format.
pub(crate) fn run_json(f: HookFn, input: &[u8]) -> Result<Vec<u8>, Error> {
    let input: HookInput =
        serde_json::from_slice(input).map_err(|e| anyhow::anyhow!("invalid hook input: {e}"))?;
    let output = f(&input)?;
    Ok(serde_json::to_vec(&output)?)
}

/// Body of every generated export. Not public API.
#[cfg(target_arch = "wasm32")]
#[doc(hidden)]
#[allow(unsafe_code)]
pub fn __run_export(f: HookFn) -> i32 {
    use extism_pdk::Memory;
    let set_error = |message: String| -> i32 {
        if let Ok(memory) = Memory::from_bytes(message) {
            // SAFETY: hands the host the offset of a live memory block, which
            // the host takes ownership of.
            unsafe { extism_pdk::extism::error_set(memory.offset()) };
        }
        1
    };
    let input = extism_pdk::input_bytes();
    match run_json(f, &input) {
        Ok(out) => match Memory::from_bytes(&out) {
            Ok(memory) => {
                memory.set_output();
                0
            }
            Err(e) => set_error(format!("{e:#}")),
        },
        Err(e) => set_error(format!("{e:#}")),
    }
}

/// Conveniences on [`HookInput`].
pub trait HookInputExt {
    /// Deserialize the settings object into your own `serde` struct whose
    /// field names are the setting keys.
    ///
    /// The host sends numbers as JSON floats (`30.0`); whole numbers are
    /// converted first so integer fields such as `u32` work.
    fn settings_as<T: DeserializeOwned>(&self) -> Result<T, Error>;

    /// The action id of an on-demand run, `None` for other events.
    fn action(&self) -> Option<&str>;

    /// The uploaded file id of an upload event, `None` for other events.
    fn uploaded_file_id(&self) -> Option<FileId>;

    /// The uploaded file's metadata: the copy in the event if the host sent
    /// one, otherwise fetched with [`crate::host::get_file`]. `Ok(None)` for
    /// other events or if the file is gone.
    fn uploaded_file(&self) -> Result<Option<FileInfo>, HostError>;
}

impl HookInputExt for HookInput {
    fn settings_as<T: DeserializeOwned>(&self) -> Result<T, Error> {
        let value = integral_numbers(Value::Object(self.settings.clone()));
        serde_json::from_value(value).map_err(|e| anyhow::anyhow!("invalid settings: {e}"))
    }

    fn action(&self) -> Option<&str> {
        match &self.event {
            HookEvent::OnDemand { action } => Some(action),
            _ => None,
        }
    }

    fn uploaded_file_id(&self) -> Option<FileId> {
        match &self.event {
            HookEvent::Upload { file_id, .. } => Some(*file_id),
            _ => None,
        }
    }

    fn uploaded_file(&self) -> Result<Option<FileInfo>, HostError> {
        match &self.event {
            HookEvent::Upload {
                file: Some(file), ..
            } => Ok(Some(file.clone())),
            HookEvent::Upload { file_id, .. } => crate::host::get_file(*file_id),
            _ => Ok(None),
        }
    }
}

/// Replace floats with no fractional part by integers, recursively.
fn integral_numbers(v: Value) -> Value {
    match v {
        Value::Number(n) if !n.is_i64() && !n.is_u64() => match n.as_f64() {
            Some(f) if f.fract() == 0.0 && f.abs() < 9.0e15 => Value::from(f as i64),
            _ => Value::Number(n),
        },
        Value::Array(a) => Value::Array(a.into_iter().map(integral_numbers).collect()),
        Value::Object(o) => Value::Object(
            o.into_iter()
                .map(|(k, v)| (k, integral_numbers(v)))
                .collect(),
        ),
        v => v,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::abi::Runner;
    use serde_json::json;

    #[test]
    fn settings_as_accepts_float_integers() {
        #[derive(serde::Deserialize)]
        struct S {
            days: u32,
            ratio: f64,
            albums: Vec<i64>,
        }
        let input = HookInput {
            event: HookEvent::OnDemand { action: "x".into() },
            settings: json!({"days": 30.0, "ratio": 0.5, "albums": [1.0, 2]})
                .as_object()
                .unwrap()
                .clone(),
            now: 0,
            runner: Runner::Test,
        };
        let s: S = input.settings_as().unwrap();
        assert_eq!((s.days, s.ratio, s.albums), (30, 0.5, vec![1, 2]));
        assert_eq!(input.action(), Some("x"));
        assert_eq!(input.uploaded_file_id(), None);
    }
}
